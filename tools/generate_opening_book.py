"""Validate curated SAN and embed compact native Move values (requires python-chess)."""
from pathlib import Path
import chess

root = Path(__file__).resolve().parents[1]
rows = []
seen = set()
for number, text in enumerate((root / 'data/opening_book.txt').read_text().splitlines(), 1):
    if not text.strip() or text.startswith('#'):
        continue
    board = chess.Board()
    moves = []
    for san in text.split():
        move = board.parse_san(san)
        flag = 3 if board.is_castling(move) else 2 if board.is_en_passant(move) else 1 if move.promotion else 0
        code = move.from_square | move.to_square << 6 | flag << 12
        if move.promotion:
            code |= (move.promotion - chess.KNIGHT) << 14
        moves.append(code)
        board.push(move)
    assert 6 <= len(moves) <= 10, (number, text)
    assert tuple(moves) not in seen, (number, 'duplicate')
    seen.add(tuple(moves))
    rows.append(moves)

size = sum(len(row) + 1 for row in rows) * 2
assert size + len(chess.STARTING_FEN) + 1 < 10_000
output = '// Generated by tools/generate_opening_book.py; do not edit.\n'
output += '#pragma once\n#include "types.h"\nnamespace OpeningBook {\n'
output += 'inline constexpr Move data[] = {\n'
output += ''.join('    ' + ', '.join(map(str, row + [0])) + ',\n' for row in rows)
output += '};\ninline constexpr size_t lineCount = ' + str(len(rows)) + ';\n'
output += 'inline constexpr int maxPly = ' + str(max(map(len, rows))) + ';\n}\n'
(root / 'src/opening_book_data.h').write_text(output, encoding='utf-8')
print(f'{len(rows)} legal lines, up to {max(map(len, rows))} plies, {size} bytes of moves and delimiters')
