# Virgin - UCI chess engine
# Extracts the published PeSTO piece square tables from the saved Chess
# Programming Wiki page (ref/pesto.html) and writes src/pst_pesto.h.
#
# Source of the tables: PeSTO's Evaluation Function by Ronald Friederich
# (engine RofChade / PeSTO), published on
#   https://chessprogramming.org/PeSTO's_Evaluation_Function
# The wiki is CC BY-SA 3.0; the tables themselves are published evaluation
# data. No source code of a GPL engine is copied by this project.
#
# The published tables use a8 = 0; this project uses a1 = 0, so the tables are
# emitted unchanged and flipped by the consumer (square ^ 56).
param(
    [string]$Html = "$PSScriptRoot\..\ref\pesto.html",
    [string]$Out  = "$PSScriptRoot\..\src\pst_pesto.h"
)

$html = Get-Content -Raw -LiteralPath $Html
if (-not $html) { throw "cannot read $Html" }

$txt = $html -replace '(?s)<script.*?</script>', '' -replace '(?s)<style.*?</style>', ''
$txt = $txt -replace '<[^>]+>', ''
$txt = $txt -replace '&gt;', '>' -replace '&lt;', '<' -replace '&amp;', '&' -replace '&quot;', '"' -replace '&#39;', "'"

function Get-Table([string]$name) {
    $re = [regex]("int\s+$name\s*\[\s*\d+\s*\]\s*=\s*\{(?<body>[^}]*)\}")
    $m = $re.Match($txt)
    if (-not $m.Success) { throw "array $name not found in $Html" }
    $nums = @()
    foreach ($tok in ($m.Groups['body'].Value -split ',')) {
        $t = $tok.Trim()
        if ($t -ne '') { $nums += [int]$t }
    }
    return $nums
}

$pieceNames = @('pawn', 'knight', 'bishop', 'rook', 'queen', 'king')
$mgValue = Get-Table 'mg_value'
$egValue = Get-Table 'eg_value'
if ($mgValue.Count -ne 6 -or $egValue.Count -ne 6) { throw 'mg_value/eg_value: expected 6 entries' }

$mg = @{}
$eg = @{}
foreach ($p in $pieceNames) {
    $mg[$p] = Get-Table "mg_${p}_table"
    $eg[$p] = Get-Table "eg_${p}_table"
    if ($mg[$p].Count -ne 64 -or $eg[$p].Count -ne 64) { throw "$p : expected 64 entries" }
}

function Format-Rows($vals) {
    $lines = @()
    for ($i = 0; $i -lt $vals.Count; $i += 8) {
        $row = @()
        for ($j = $i; $j -lt [Math]::Min($i + 8, $vals.Count); ++$j) {
            $row += ('{0,5}' -f $vals[$j])
        }
        $lines += '    ' + (($row -join ',') + ',')
    }
    return $lines
}

function Format-Flat($vals) {
    $row = @()
    foreach ($v in $vals) { $row += ('{0,5}' -f $v) }
    return '    ' + (($row -join ',') + ',')
}

$o = @()
$o += '// Virgin - UCI chess engine'
$o += '// PeSTO piece square tables and material values, as published by Ronald'
$o += '// Friederich (engines RofChade / PeSTO) on the Chess Programming Wiki:'
$o += '//   https://chessprogramming.org/PeSTO''s_Evaluation_Function'
$o += '// Generated by tools/extract_pesto.ps1 - do not edit by hand.'
$o += '//'
$o += '// These are published evaluation *data* (CC BY-SA 3.0 wiki, tables by the'
$o += '// author). No source code of any GPL engine is used in this project.'
$o += '//'
$o += '// Index convention: as published, a8 = 0. This engine uses a1 = 0, so the'
$o += '// consumer flips with (square ^ 56) before use.'
$o += '#pragma once'
$o += ''
$o += '// Order: PAWN, KNIGHT, BISHOP, ROOK, QUEEN, KING'
$o += 'constexpr int PESTO_MG_VALUE[6] = {'
$o += (Format-Flat $mgValue)
$o += '};'
$o += 'constexpr int PESTO_EG_VALUE[6] = {'
$o += (Format-Flat $egValue)
$o += '};'
$o += ''
$o += 'constexpr int PESTO_MG[6][64] = {'
foreach ($p in $pieceNames) {
    $o += "    {  // $p"
    $o += (Format-Rows $mg[$p])
    $o += '    },'
}
$o += '};'
$o += ''
$o += 'constexpr int PESTO_EG[6][64] = {'
foreach ($p in $pieceNames) {
    $o += "    {  // $p"
    $o += (Format-Rows $eg[$p])
    $o += '    },'
}
$o += '};'
$o += ''

$o -join "`r`n" | Set-Content -Encoding ascii -LiteralPath $Out
"wrote $Out  ($($mgValue.Count) material mg, $(($pieceNames | ForEach-Object { $mg[$_].Count }) -join '/') squares per piece)"
